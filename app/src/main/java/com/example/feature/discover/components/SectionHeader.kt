@Composable
fun SectionHeader(title: String, subtitle: String? = null, actionText: String? = null, onActionClick: () -> Unit = {}) {
    LaunchedEffect(title) {
        DiscoverAnalytics.sectionViewed(title)
    }

    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(horizontal = 16.dp, vertical = 8.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.Bottom
    ) {
        Column {
            Text(
                text = title,
                style = MaterialTheme.typography.titleLarge,
                fontWeight = FontWeight.Bold,
                color = MaterialTheme.colorScheme.onBackground
            )
            if (subtitle != null) {
                Text(
                    text = subtitle,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
        }
        if (actionText != null) {
            val displayedActionText = if (actionText.equals("See all", ignoreCase = true)) "See all →" else actionText
            Text(
                text = displayedActionText,
                style = MaterialTheme.typography.labelLarge,
                color = MaterialTheme.colorScheme.primary,
                fontWeight = FontWeight.Bold,
                modifier = Modifier
                    .semantics {
                        contentDescription = "$title $displayedActionText"
                        role = Role.Button
                    }
                    .clickable {
                        DiscoverAnalytics.seeAllClicked(title)
                        onActionClick()
                    }
            )
        }
    }
}
